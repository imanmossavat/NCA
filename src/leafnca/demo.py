"""Demo: growth, stability, three damages and self-healing -> GIF + key-frame strip.

  python -m leafnca.demo --ckpt results/model.pt --out results
"""
import argparse
import json
import os

import imageio.v2 as imageio
import numpy as np
import PIL.Image
import PIL.ImageDraw
import torch

from . import damage as D
from . import model as M
from .metrics import mse, to_image
from .targets import load_target
from .utils import get_device, git_sha, setup_threads


def frame(x, caption, scale=6):
    img = to_image(x)
    im = PIL.Image.fromarray(img).resize((img.shape[1] * scale, img.shape[0] * scale), PIL.Image.NEAREST)
    out = PIL.Image.new("RGB", (im.width, im.height + 20), (255, 255, 255))
    out.paste(im, (0, 0))
    PIL.ImageDraw.Draw(out).text((4, im.height + 4), caption, fill=(0, 0, 0))
    return out


def with_footer(im, text):
    out = PIL.Image.new("RGB", (im.width, im.height + 16), (255, 255, 255))
    out.paste(im, (0, 0))
    PIL.ImageDraw.Draw(out).text((4, im.height + 2), text, fill=(110, 110, 110))
    return out


@torch.no_grad()
def demo(a):
    setup_threads()
    dev = get_device(a.device)
    torch.manual_seed(a.seed)
    ca, ck = M.load(a.ckpt, dev)
    target = load_target(ck.get("target", "leaf"), device=dev)
    H = target.shape[-1]
    frames, keys, metrics = [], [], {}

    def run(x, n, label, every=3):
        for t in range(n):
            x = ca(x)
            if t % every == 0:
                frames.append(frame(x, f"{label} t={t}"))
        return x

    def err(x):
        return round(mse(x, target).item(), 6)

    damages = [("half-cut", lambda x: D.cut_half(x, 0.0)),
               ("circle-hole", lambda x: D.cut_circle(x, H // 2 - 6, H // 2 + 4, 9)),
               ("40%-random-erase", lambda x: D.erase_random(x, 0.4))]

    keys.append(frame(target, "target"))
    x = run(M.seed(1, H, device=dev), a.grow, "grow"); keys.append(frame(x, f"grown t={a.grow}"))
    metrics["grown"] = err(x)
    x = run(x, a.hold, "hold", every=10); keys.append(frame(x, f"held +{a.hold}")); metrics["after_hold"] = err(x)
    for name, fn in damages:
        xd = fn(x); keys.append(frame(xd, f"damaged: {name}")); metrics[f"{name} damaged"] = err(xd)
        for _ in range(8):
            frames.append(frame(xd, f"damaged: {name}"))  # pause on the damage
        x = run(xd, a.heal, f"heal {name}"); keys.append(frame(x, f"healed: {name}"))
        metrics[f"{name} healed"] = err(x)

    os.makedirs(a.out, exist_ok=True)
    imageio.mimsave(f"{a.out}/demo.gif", [np.array(f) for f in frames], duration=0.06, loop=0)
    strip = PIL.Image.new("RGB", (sum(k.width for k in keys), keys[0].height), (255, 255, 255))
    xo = 0
    for k in keys:
        strip.paste(k, (xo, 0)); xo += k.width
    with_footer(strip, f"generated by python -m leafnca.demo at commit {git_sha()} (torch seed {a.seed})"
                ).save(f"{a.out}/demo_strip.png")
    with open(f"{a.out}/demo_metrics.json", "w") as f:
        json.dump({"mse": metrics, "seed": a.seed, "commit": git_sha(), "ckpt": a.ckpt,
                   "grow": a.grow, "hold": a.hold, "heal": a.heal}, f, indent=2)
    print("MSE vs target (lower = better):")
    for k, v in metrics.items():
        print(f"  {k:28s} {v:.5f}")
    print(f"wrote {a.out}/demo.gif and {a.out}/demo_strip.png")


def parser():
    d = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    d.add_argument("--ckpt", default="results/model.pt"); d.add_argument("--out", default="results")
    d.add_argument("--grow", type=int, default=120); d.add_argument("--hold", type=int, default=200)
    d.add_argument("--heal", type=int, default=150); d.add_argument("--seed", type=int, default=0)
    d.add_argument("--device", default=None)
    return d


if __name__ == "__main__":
    demo(parser().parse_args())
