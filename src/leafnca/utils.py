"""Device selection and provenance helpers."""
import subprocess
from pathlib import Path

import torch

ROOT = Path(__file__).resolve().parents[2]


def get_device(name=None):
    if name:
        return torch.device(name)
    if torch.backends.mps.is_available():
        return torch.device("mps")  # Apple Silicon GPU
    return torch.device("cpu")


def setup_threads():
    torch.set_num_threads(4)  # leave cores free so the laptop stays usable


def git_sha():
    """Short commit hash of the repo, with '-dirty' if tracked files have uncommitted changes."""
    try:
        sha = subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, text=True).strip()
        dirty = subprocess.run(["git", "diff", "--quiet", "HEAD", "--", "src", "experiments"], cwd=ROOT).returncode
        return sha + ("-dirty" if dirty else "")
    except Exception:
        return "unknown"


def stamp(fig, script):
    """Label a matplotlib figure with the script and commit that produced it."""
    fig.text(0.99, 0.005, f"generated by {script} at commit {git_sha()}", ha="right", va="bottom",
             fontsize=7, color="0.4")
