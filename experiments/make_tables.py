"""Render every results/*/summary.csv (and the demo metrics) as markdown tables -> results/tables.md.

REPORT.md tables are pasted from this file, never typed by hand.
"""
import csv
import json

from common import ROOT
from leafnca.utils import git_sha

R = ROOT / "results"


def md(rows):
    keys = list(rows[0].keys())
    out = ["| " + " | ".join(keys) + " |", "|" + "---|" * len(keys)]
    out += ["| " + " | ".join(str(r[k]) for k in keys) + " |" for r in rows]
    return "\n".join(out)


parts = [f"<!-- generated by experiments/make_tables.py at commit {git_sha()} -->"]
demo = json.load(open(R / "demo_metrics.json"))
parts += ["## demo (results/demo_metrics.json)",
          md([{"stage": k, "mse": v} for k, v in demo["mse"].items()]) + f"\n\nseed {demo['seed']}, commit {demo['commit']}"]
for d in sorted(R.glob("0*")):
    if not (d / "summary.json").exists():
        continue  # experiment not run (yet)
    js = json.load(open(d / "summary.json"))
    if (d / "summary.csv").exists():
        body = md(list(csv.DictReader(open(d / "summary.csv"))))
    else:  # experiment 1 has a flat summary
        body = md([{k: v for k, v in js.items() if not isinstance(v, (dict, list))}])
    extra = {k: v for k, v in js.items() if isinstance(v, dict)}
    parts += [f"## {d.name}", body + "".join(f"\n\n{k}: `{json.dumps(v)}`" for k, v in extra.items())
              + f"\n\nscript {js.get('script')}, commit {js.get('commit')}, seed {js.get('seed', '-')}"]
(R / "tables.md").write_text("\n\n".join(parts) + "\n")
print((R / "tables.md").read_text())
